use std::env;
use std::fs::File;
use std::io::{self, BufWriter, Write};
use std::path::{Path, PathBuf};

type Bitboard = u64;

const fn file_of(sq: i32) -> i32 {
    sq & 7
}
fn in_board(sq: i32) -> bool {
    (0..64).contains(&sq)
}

struct Rng(u64);
impl Rng {
    const fn new() -> Self {
        Self(0x1234_5678_9ABC_DEF0)
    }
    const fn rand(&mut self) -> u64 {
        self.0 ^= self.0 >> 12;
        self.0 ^= self.0 << 25;
        self.0 ^= self.0 >> 27;
        self.0.wrapping_mul(0x2545_F491_4F6C_DD1D)
    }
    const fn rand_sparse(&mut self) -> u64 {
        self.rand() & self.rand() & self.rand()
    }
}

fn slider_mask(sq: usize, is_rook: bool) -> Bitboard {
    let mut result = 0;
    let r = sq / 8;
    let f = sq % 8;
    let deltas = if is_rook {
        [(1, 0), (-1, 0), (0, 1), (0, -1)]
    } else {
        [(1, 1), (1, -1), (-1, 1), (-1, -1)]
    };
    for (dr, df) in deltas {
        let (mut cr, mut cf) = (r as i32 + dr, f as i32 + df);
        while (0..8).contains(&cr) && (0..8).contains(&cf) {
            let next_r = cr + dr;
            let next_f = cf + df;
            if (0..8).contains(&next_r) && (0..8).contains(&next_f) {
                result |= 1u64 << (cr * 8 + cf) as usize;
            }
            cr += dr;
            cf += df;
        }
    }
    result
}

fn slider_attacks(sq: usize, blockers: Bitboard, is_rook: bool) -> Bitboard {
    let mut attacks = 0;
    let r = sq / 8;
    let f = sq % 8;
    let deltas = if is_rook {
        [(1, 0), (-1, 0), (0, 1), (0, -1)]
    } else {
        [(1, 1), (1, -1), (-1, 1), (-1, -1)]
    };
    for (dr, df) in deltas {
        let (mut cr, mut cf) = (r as i32 + dr, f as i32 + df);
        while (0..8).contains(&cr) && (0..8).contains(&cf) {
            let to_sq = (cr * 8 + cf) as usize;
            attacks |= 1u64 << to_sq;
            if (blockers & (1u64 << to_sq)) != 0 {
                break;
            }
            cr += dr;
            cf += df;
        }
    }
    attacks
}

/// A square's magic: blockers masked by `mask` and multiplied by `magic`,
/// shifted right by `shift`, index `table`.
struct FoundMagic {
    mask: Bitboard,
    magic: u64,
    shift: u32,
    table: Vec<Bitboard>,
}

fn find_magic_for_sq(sq: usize, is_rook: bool, rng: &mut Rng) -> FoundMagic {
    let mask = slider_mask(sq, is_rook);
    let bits = mask.count_ones();
    let table_size = 1 << bits;
    let mut occupancies = Vec::with_capacity(table_size);
    let mut attacks = Vec::with_capacity(table_size);
    let mut b: Bitboard = 0;
    loop {
        occupancies.push(b);
        attacks.push(slider_attacks(sq, b, is_rook));
        b = (b.wrapping_sub(mask)) & mask;
        if b == 0 {
            break;
        }
    }
    loop {
        let magic = rng.rand_sparse();
        if (mask.wrapping_mul(magic) >> 56).count_ones() < 6 {
            continue;
        }
        let mut used_indices: Vec<Option<u64>> = vec![None; table_size];
        let mut collision = false;
        for i in 0..table_size {
            let occ = occupancies[i];
            let index = (occ.wrapping_mul(magic) >> (64 - bits)) as usize;
            let current_attack = attacks[i];
            if let Some(existing_attack) = used_indices[index] {
                if existing_attack != current_attack {
                    collision = true;
                    break;
                }
            } else {
                used_indices[index] = Some(current_attack);
            }
        }
        if !collision {
            let mut table = vec![0; table_size];
            for i in 0..table_size {
                let occ = occupancies[i];
                let index = (occ.wrapping_mul(magic) >> (64 - bits)) as usize;
                table[index] = attacks[i];
            }
            return FoundMagic {
                mask,
                magic,
                shift: 64 - bits,
                table,
            };
        }
    }
}

const WHITE_PAWN_DELTAS: [i32; 2] = [7, 9];
const BLACK_PAWN_DELTAS: [i32; 2] = [-9, -7];
const KNIGHT_DELTAS: [i32; 8] = [6, 10, 15, 17, -6, -10, -15, -17];
const KING_DELTAS: [i32; 8] = [1, -1, 8, -8, 7, 9, -7, -9];

/// Generates all attack tables and writes them to a single .rs file.
fn generate_attacks_source(out_dir: &Path) -> io::Result<()> {
    let mut f = BufWriter::new(File::create(out_dir.join("generated_attacks.rs"))?);
    writeln!(
        f,
        "// This file is generated by build.rs. Do not edit by hand."
    )?;
    for (name, deltas, max_file_step) in [
        ("WHITE_PAWN_ATTACKS", &WHITE_PAWN_DELTAS[..], 1),
        ("BLACK_PAWN_ATTACKS", &BLACK_PAWN_DELTAS[..], 1),
        ("KNIGHT_ATTACKS", &KNIGHT_DELTAS[..], 2),
        ("KING_ATTACKS", &KING_DELTAS[..], 1),
    ] {
        let table: [Bitboard; 64] =
            std::array::from_fn(|sq| leaper_attacks(sq as i32, deltas, max_file_step));
        write_leaper_table(&mut f, name, &table)?;
    }

    let mut rng = Rng::new();
    let rooks: Vec<FoundMagic> = (0..64)
        .map(|sq| find_magic_for_sq(sq, true, &mut rng))
        .collect();
    let bishops: Vec<FoundMagic> = (0..64)
        .map(|sq| find_magic_for_sq(sq, false, &mut rng))
        .collect();
    write_slider_tables(&mut f, "ROOK", &rooks)?;
    write_slider_tables(&mut f, "BISHOP", &bishops)?;
    Ok(())
}

/// The squares a piece on `sq` reaches by `deltas`, each moving at most
/// `max_file_step` files sideways so that none wraps around the board.
fn leaper_attacks(sq: i32, deltas: &[i32], max_file_step: i32) -> Bitboard {
    deltas
        .iter()
        .map(|d| sq + d)
        .filter(|&to| in_board(to) && (file_of(sq) - file_of(to)).abs() <= max_file_step)
        .fold(0, |attacks, to| attacks | 1u64 << to)
}

/// Writes `name`, a table of one bitboard per square, eight to a line.
fn write_leaper_table(f: &mut impl Write, name: &str, table: &[Bitboard; 64]) -> io::Result<()> {
    writeln!(f, "\npub const {name}: [Bitboard; 64] = [")?;
    for (i, &attack) in table.iter().enumerate() {
        write!(f, "0x{attack:X},")?;
        if (i + 1) % 8 == 0 {
            writeln!(f)?;
        }
    }
    writeln!(f, "];")
}

/// Writes `{name}_MAGICS`, one `Magic` per square, and `{name}_ATTACKS`, the
/// squares' tables end to end at the offsets the magics give.
fn write_slider_tables(f: &mut impl Write, name: &str, found: &[FoundMagic]) -> io::Result<()> {
    writeln!(f, "\nconst {name}_MAGICS: [Magic; 64] = [")?;
    let mut offset = 0;
    for square in found {
        writeln!(
            f,
            "    Magic {{ mask: 0x{:X}, magic: 0x{:X}, shift: {}, offset: {offset} }},",
            square.mask, square.magic, square.shift
        )?;
        offset += square.table.len();
    }
    writeln!(f, "];")?;

    writeln!(f, "\npub static {name}_ATTACKS: [Bitboard; {offset}] = [")?;
    for (i, attack) in found.iter().flat_map(|square| &square.table).enumerate() {
        write!(f, "0x{attack:016X},")?;
        if (i + 1) % 8 == 0 {
            writeln!(f)?;
        }
    }
    writeln!(f, "];")
}

const fn splitmix64(state: &mut u64) -> u64 {
    *state = state.wrapping_add(0x9E37_79B9_7F4A_7C15);
    let mut x = *state;
    x = (x ^ (x >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
    x = (x ^ (x >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
    x ^ (x >> 31)
}

fn generate_zobrist_keys(out_dir: &Path) -> io::Result<()> {
    let dest_path = out_dir.join("generated_zobrist.rs");
    let mut f = BufWriter::new(File::create(&dest_path)?);

    writeln!(
        f,
        "// This file is generated by build.rs. Do not edit by hand."
    )?;
    writeln!(f, "use crate::types::ZKey;")?;

    let mut seed: u64 = 0x1234_5678_9ABC_DEF0;

    // Generate the keys
    writeln!(f, "\npub const ZOBRIST_KEYS: Zobrist = Zobrist {{")?;

    // Piece keys
    writeln!(f, "    piece: [")?;
    for _ in 0..13 {
        writeln!(f, "        [")?;
        for _ in 0..64 {
            writeln!(f, "            0x{:016X},", splitmix64(&mut seed))?;
        }
        writeln!(f, "        ],")?;
    }
    writeln!(f, "    ],")?;

    // Castle keys
    writeln!(f, "    castle: [")?;
    for _ in 0..16 {
        writeln!(f, "        0x{:016X},", splitmix64(&mut seed))?;
    }
    writeln!(f, "    ],")?;

    // EP file keys
    writeln!(f, "    ep_file: [")?;
    for _ in 0..8 {
        writeln!(f, "        0x{:016X},", splitmix64(&mut seed))?;
    }
    writeln!(f, "    ],")?;

    // Side key
    writeln!(f, "    side: 0x{:016X},", splitmix64(&mut seed))?;

    writeln!(f, "}};")?;
    Ok(())
}

fn main() -> io::Result<()> {
    let out_dir = env::var_os("OUT_DIR")
        .map(PathBuf::from)
        .ok_or_else(|| io::Error::other("cargo did not set OUT_DIR"))?;
    generate_attacks_source(&out_dir)?;
    generate_zobrist_keys(&out_dir)?;
    println!("cargo:rerun-if-changed=build.rs");
    Ok(())
}
